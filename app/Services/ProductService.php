    public static function all(): array
    {
        return self::$products;
    }

    public static function find(int $id): ?array
    {
        return self::$products[$id] ?? null;
    }

    public static function search(?string $query = null, ?string $category = null, ?string $sugarLevel = null): array
    {
        $filtered = self::$products;

        if ($query) {
            $q = mb_strtolower(trim($query));
            $filtered = array_filter($filtered, function ($item) use ($q) {
                return str_contains(mb_strtolower($item['name']), $q)
                    || str_contains(mb_strtolower($item['brand']), $q)
                    || str_contains(mb_strtolower($item['category_name']), $q);
            });
        }

        if ($category && $category !== 'all') {
            $filtered = array_filter($filtered, function ($item) use ($category) {
                return $item['category_type'] === $category;
            });
        }

        if ($sugarLevel && $sugarLevel !== 'all') {
            $filtered = array_filter($filtered, function ($item) use ($sugarLevel) {
                return $item['sugar_level'] === strtoupper($sugarLevel);
            });
        }

        return $filtered;
    }

    public static function lowSugarProducts(int $limit = 6): array
    {
        $lows = array_filter(self::$products, function ($item) {
            return $item['sugar_level'] === 'RENDAH';
        });

        return array_slice($lows, 0, $limit);
    }

